# -*- coding: utf-8 -*-
"""verify_data.py —— 公开数据完整性自检（不碰 GPU）

检查两个场景：照片数、EXIF 是否已清除、位姿数、点云规模、高度覆盖与范围、
held-out 切分数（是否与论文口径一致），并可写出 data/MANIFEST.md 的哈希清单。

用法：
    python src/verify_data.py                 # 只自检
    python src/verify_data.py --manifest      # 自检 + 生成 data/MANIFEST.md
"""

import argparse
import glob
import hashlib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from paths import DATA_ROOT  # noqa: E402
from mini_train import read_colmap_txt  # noqa: E402
from read_altitude import read_xmp  # noqa: E402

SCENES = {
    "fieldH": {"images": 331, "poses": 329, "points": 137229, "heldout": 41,
               "res": (1152, 2048)},
    "jxfx": {"images": 117, "poses": 117, "points": 78192, "heldout": 14,
             "res": (1152, 2048)},
}


def has_exif(path):
    head = open(path, "rb").read(65536)
    return b"Exif" in head or b"xpacket" in head


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def check(scene, expect):
    root = os.path.join(DATA_ROOT, scene)
    rows, ok = [], True

    imgs = sorted(glob.glob(os.path.join(root, "images", "*")))
    n_img = len(imgs)
    exif = sum(has_exif(p) for p in imgs)
    sizes = {os.path.getsize(p) for p in imgs}
    rows.append(("照片数", n_img, expect["images"], n_img == expect["images"]))
    rows.append(("带 EXIF/XMP 的照片", exif, 0, exif == 0))

    cams, poses, pts, _ = read_colmap_txt(os.path.join(root, "sparse", "0"))
    rows.append(("相机条目", len(cams), "≥ 1（每图或共用）", len(cams) >= 1))
    rows.append(("位姿数", len(poses), expect["poses"], len(poses) == expect["poses"]))
    rows.append(("SfM 点数", len(pts), expect["points"], len(pts) == expect["points"]))
    rows.append(("held-out 视角", len(list(range(7, len(poses), 8))), expect["heldout"],
                 len(list(range(7, len(poses), 8))) == expect["heldout"]))

    rels = [read_xmp(p)[0] for p in imgs]
    miss = sum(r is None for r in rels)
    have = [r for r in rels if r is not None]
    rows.append(("有高度的照片", len(have), n_img, miss == 0))
    if have:
        rows.append(("相对高度范围 m", "%.1f – %.1f" % (min(have), max(have)), "> 0", True))

    for name, got, want, passed in rows:
        ok &= passed
        print("  %-18s %-16s 期望 %-14s %s" % (name, got, want, "OK" if passed else "FAIL"))
    print("  → %s: %s" % (scene, "PASS" if ok else "FAIL"))
    return ok, imgs, poses, rels


def manifest(imgs, dirname):
    """整目录哈希（逐字节拼接后 sha256）+ 单文件清单"""
    h = hashlib.sha256()
    for p in imgs:
        h.update(os.path.basename(p).encode())
        h.update(sha256(p).encode())
    return h.hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", action="store_true", help="写出 data/MANIFEST.md")
    args = ap.parse_args()

    all_ok = True
    cache = {}
    for scene, expect in SCENES.items():
        print("\n=== %s ===" % scene)
        ok, imgs, poses, rels = check(scene, expect)
        all_ok &= ok
        cache[scene] = (imgs, poses, rels)

    if args.manifest:
        out = os.path.join(DATA_ROOT, "MANIFEST.md")
        lines = ["# Data manifest", "",
                 "Generated by `python src/verify_data.py --manifest`. "
                 "Hashes cover the released copies only (metadata already stripped).", "",
                 "| Scene | Images | Poses | Points | Held-out | Images SHA-256 |", "|---|---|---|---|---|---|"]
        for scene, (imgs, poses, rels) in cache.items():
            sp = os.path.join(DATA_ROOT, scene, "sparse", "0")
            pts = len(read_colmap_txt(sp)[2])
            lines.append("| `%s` | %d | %d | %d | %d | `%s` |" % (
                scene, len(imgs), len(poses), pts, len(list(range(7, len(poses), 8))),
                manifest(imgs, scene)))
        lines += ["", "Sparse models (`cameras.txt`, `images.txt`, `points3D.txt`) and "
                  "`altitude.csv` are small text files; hash them with `sha256sum` if needed.", ""]
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines))
        print("\nMANIFEST → %s" % out)

    print("\nVERIFY_OK" if all_ok else "\nVERIFY_FAILED")
    return 0 if all_ok else 1


if __name__ == "__main__":
    sys.exit(main())
